# Refuses to start a gateway on a port something else is already serving.
#
# Without this, a leftover gateway from an aborted run is *healthy* on the
# port the new one wants, `eval_wait_gateway` succeeds against it, and every
# request then goes to a process pointed at a scratch database that no
# longer exists — which arrives as a 401 on the first governed call and
# reads like a broken token. It cost two demo runs to diagnose, so the
# collision names itself now (EVAL-5).
eval_port_free() {
  eval_free_url=$1
  eval_free_port=$(eval_loopback_port "$eval_free_url" bind-probe) || return 1
  if python3 - "$eval_free_port" >/dev/null 2>&1 <<'PY'
import socket
import sys

sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
try:
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind(("127.0.0.1", int(sys.argv[1])))
finally:
    sock.close()
PY
  then
    return 0
  fi
  echo "eval: something is already listening on $eval_free_url — most likely an eval process" >&2
  echo "      left behind by an aborted run. Stop that process before retrying." >&2
  return 1
}

eval_process_live() {
  case "$1" in
    ''|*[!0-9]*|0|1) return 1 ;;
    *) kill -0 "$1" 2>/dev/null ;;
  esac
}

eval_surface_process_log() { # label log-file
  echo "eval: $1 process exited before readiness" >&2
  if [ -f "$2" ] && [ ! -L "$2" ]; then
    echo "eval: last $1 log lines:" >&2
    tail -n 40 "$2" >&2 || true
  fi
}

eval_wait_ready() { # label URL PID log-file
  eval_ready_label=$1
  eval_ready_url=$2
  eval_ready_pid=$3
  eval_ready_log=$4
  tries=0
  while [ "$tries" -lt 30 ]; do
    eval_process_live "$eval_ready_pid" || {
      eval_surface_process_log "$eval_ready_label" "$eval_ready_log"
      return 1
    }
    if eval_curl_probe -fsS "$eval_ready_url/readyz" >/dev/null 2>&1; then
      eval_process_live "$eval_ready_pid" || {
        eval_surface_process_log "$eval_ready_label" "$eval_ready_log"
        return 1
      }
      return 0
    fi
    eval_process_live "$eval_ready_pid" || {
      eval_surface_process_log "$eval_ready_label" "$eval_ready_log"
      return 1
    }
    tries=$((tries + 1))
    sleep 1
  done
  echo "eval: $eval_ready_label did not become ready on $eval_ready_url" >&2
  return 1
}

eval_wait_gateway() {
  eval_wait_ready gateway "$@"
}

eval_wait_worker() {
  eval_wait_ready worker "$@"
}

