EVAL_SEED_PID=
EVAL_WORKER_PID=

eval_loopback_port() { # URL label
  eval_loopback_url=$1
  eval_loopback_label=$2
  case "$eval_loopback_url" in
    http://127.0.0.1:*) eval_loopback_port_value=${eval_loopback_url#http://127.0.0.1:} ;;
    *)
      echo "eval: $eval_loopback_label URL must be canonical loopback HTTP" >&2
      return 1
      ;;
  esac
  case "$eval_loopback_port_value" in
    ''|0|0[0-9]*|*[!0-9]*)
      echo "eval: $eval_loopback_label URL must declare one canonical port" >&2
      return 1
      ;;
    *) ;;
  esac
  [ "$eval_loopback_port_value" -le 65535 ] || {
    echo "eval: $eval_loopback_label URL port is outside 1..65535" >&2
    return 1
  }
  printf '%s\n' "$eval_loopback_port_value"
}

# The product default remains one hour. LongMemEval is the one deterministic
# run whose supported-API seed plus post-seed extraction wait can cross that
# boundary, so its disposable gateway and only its lme-* actors share an
# explicit longer bound. This does not bypass AUTH-3: the gateway still checks
# exp - iat against the configured ceiling on every governed call.
eval_service_token_ttl_for_run() {
  eval_token_actor_count=${EVAL_LONGMEMEVAL_ACTORS:-0}
  case "$eval_token_actor_count" in
    ''|*[!0-9]*)
      echo "eval: EVAL_LONGMEMEVAL_ACTORS must be a non-negative integer" >&2
      return 1
      ;;
  esac
  if [ "$eval_token_actor_count" -gt 0 ]; then
    eval_token_ttl=${EVAL_LONGMEMEVAL_TOKEN_TTL_SECS:-7200}
  else
    eval_token_ttl=3600
  fi
  case "$eval_token_ttl" in
    ''|*[!0-9]*|0)
      echo "eval: LongMemEval token TTL must be a positive integer" >&2
      return 1
      ;;
  esac
  printf '%s\n' "$eval_token_ttl"
}

eval_json_field() {
  node -e '
    let d = "";
    process.stdin.on("data", (c) => (d += c));
    process.stdin.on("end", () => {
      let v = JSON.parse(d);
      for (const k of process.argv.slice(1)) v = v[k];
      if (v === undefined) process.exit(1);
      console.log(typeof v === "string" ? v : JSON.stringify(v));
    });
  ' "$@"
}

# Every request in this fixture targets one validated loopback URL. Disable
# ambient curl configuration before any other option, refuse proxy routing and
# bound both connection establishment and the whole request.
eval_curl() {
  command curl --disable --noproxy '*' --connect-timeout 2 --max-time 30 "$@"
}

eval_curl_probe() {
  eval_curl --connect-timeout 1 --max-time 1 "$@"
}

# Keep bearer credentials out of curl's argv. Tokens are generated by this
# fixture and use the closed JWT/base64url vocabulary before entering a
# one-request stdin configuration.
eval_bearer_curl() (
  eval_bearer_token=$1
  shift
  case "$eval_bearer_token" in
    ''|*[!A-Za-z0-9_.-]*)
      echo "eval: refusing malformed bearer credential" >&2
      return 1
      ;;
  esac
  printf 'header = "Authorization: Bearer %s"\n' "$eval_bearer_token" |
    eval_curl --config - "$@"
)

