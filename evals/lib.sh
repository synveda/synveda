EVAL_SEED_URL=${EVAL_SEED_URL:-http://127.0.0.1:8151}
EVAL_WORKER_URL=${EVAL_WORKER_URL:-http://127.0.0.1:8152}

# This sourced library owns these values. Never let an inherited path or PID
# become a cleanup target when preflight refuses before the fixture starts.
