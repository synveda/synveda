# eval_longmemeval [extra args…] — the deterministic retrieval tier
# (EVAL-3, ADR-0061 decision 5) against the stack eval_up made. Its own
# baseline and its own report, because it grades a different predicate
# from the four suites `eval_run` carries: those ask what a block did with
# a corpus this repository wrote, and this one asks whether a block bound
# the evidence sessions somebody else's benchmark names.
eval_longmemeval() {
  ./target/debug/synveda-eval longmemeval \
    --env "$EVAL_ENV" \
    ${EVAL_LONGMEMEVAL_CORPUS:+--corpus "$EVAL_LONGMEMEVAL_CORPUS"} \
    --instances "${EVAL_LONGMEMEVAL_INSTANCES:-10}" \
    --seed-timeout-secs "${EVAL_LONGMEMEVAL_SEED_TIMEOUT:-1800}" \
    ${EVAL_LONGMEMEVAL_JUDGED:+--judged} \
    ${EVAL_BASELINE:+--baseline "$EVAL_BASELINE"} \
    --report "${EVAL_REPORT:-$EVAL_STATE/longmemeval.json}" \
    "$@"
}

# eval_run [extra args…] — the harness against the stack eval_up made.
# $EVAL_REPORT names where the JSON report lands; the default goes with
# the run's scratch state, and CI points it somewhere it can keep.
# $EVAL_BASELINE picks the gate: the default is the deterministic one, and
# `make eval-extraction-live` points it at evals/baseline-live.json,
# because a live model's numbers and a ruleset's are not comparable
# (EVAL-2, ADR-0046 decision 12).
eval_run() {
  ./target/debug/synveda-eval run \
    --env "$EVAL_ENV" \
    --suite evals/scenarios \
    --fixtures evals/fixtures/extraction \
    --qa evals/fixtures/qa \
    --security evals/fixtures/security \
    ${EVAL_SECURITY_VARIANTS:+--security-variants "$EVAL_SECURITY_VARIANTS"} \
    --baseline "${EVAL_BASELINE:-evals/baseline.json}" \
    --report "${EVAL_REPORT:-$EVAL_STATE/report.json}" \
    ${EVAL_DENSE_RETRIEVAL:+--dense-retrieval} \
    "$@"
}

eval_stop_pids_with_grace() { # bounded ticks followed by PIDs
  eval_stop_limit=$1
  shift
  case "$eval_stop_limit" in
    ''|*[!0-9]*|0) return 64 ;;
    *) [ "$eval_stop_limit" -le 120 ] || return 64 ;;
  esac
  eval_stop_targets=
  for eval_stop_target do
    case "$eval_stop_target" in
      ''|*[!0-9]*|0|1) continue ;;
      *) eval_stop_targets="$eval_stop_targets $eval_stop_target" ;;
    esac
    kill -TERM "$eval_stop_target" 2>/dev/null || true
  done

  eval_stop_tick=0
  while [ "$eval_stop_tick" -lt "$eval_stop_limit" ]; do
    eval_stop_alive=0
    for eval_stop_target in $eval_stop_targets; do
      if kill -0 "$eval_stop_target" 2>/dev/null; then
        eval_stop_alive=1
      fi
    done
    if [ "$eval_stop_alive" -eq 0 ]; then
      break
    fi
    eval_stop_tick=$((eval_stop_tick + 1))
    sleep 0.1
  done

  for eval_stop_target in $eval_stop_targets; do
    if kill -0 "$eval_stop_target" 2>/dev/null; then
      kill -KILL "$eval_stop_target" 2>/dev/null || true
    fi
  done
  for eval_stop_target in $eval_stop_targets; do
    wait "$eval_stop_target" 2>/dev/null || true
  done
  return 0
}

eval_stop_pids() {
  eval_stop_pids_with_grace 120 "$@"
}

eval_down() {
  eval_gateway_pid=$EVAL_PID
  eval_worker_pid=$EVAL_WORKER_PID
  eval_seed_pid=$EVAL_SEED_PID
  EVAL_PID=
  EVAL_WORKER_PID=
  EVAL_SEED_PID=
  eval_stop_pids "$eval_gateway_pid" "$eval_worker_pid" "$eval_seed_pid"
  eval_owned_state=$EVAL_STATE
  eval_owned_parent=$EVAL_STATE_PARENT
  eval_owned_flag=$EVAL_STATE_OWNED
  if [ "$eval_owned_flag" = 1 ]; then
    case "$eval_owned_parent" in
      /*) ;;
      *)
        echo "eval: refused scratch state with a non-absolute parent" >&2
        return 1
        ;;
    esac
    [ "$eval_owned_parent" != / ] || {
      echo "eval: refused scratch state under the filesystem root" >&2
      return 1
    }
    case "$eval_owned_state" in
      "$eval_owned_parent"/synveda-eval.*) ;;
      *)
        echo "eval: refused to remove unowned scratch state" >&2
        return 1
        ;;
    esac
    [ -d "$eval_owned_state" ] && [ ! -L "$eval_owned_state" ] || {
      echo "eval: refused missing or replaced scratch state" >&2
      return 1
    }
  fi
  # The enclosing exact-role database fixture owns volumes and cleanup.
  # The gateway's log is the only place a run that committed nothing says
  # why, and until now it lived in scratch state this function deletes —
  # so the nightly of 2026-08-01 reported zero records across every corpus
  # and threw away the one file that knew the reason. When the report has a
  # home outside the scratch state, which is what CI gives it, the logs go
  # with it: the run that needs them is by definition one that already
  # failed.
  if [ "$eval_owned_flag" = 1 ] && [ -n "${EVAL_REPORT:-}" ]; then
    eval_report_dir=$(dirname "$EVAL_REPORT")
    if [ -d "$eval_report_dir" ]; then
      for eval_log_file in "$eval_owned_state"/*.log; do
        if [ -f "$eval_log_file" ] && [ ! -L "$eval_log_file" ]; then
          cp "$eval_log_file" "$eval_report_dir" 2>/dev/null || true
        fi
      done
    fi
  fi
  if [ -n "${EVAL_KEEP_STATE:-}" ] && [ "$eval_owned_flag" = 1 ]; then
    echo "eval: state kept at $eval_owned_state" >&2
  elif [ "$eval_owned_flag" = 1 ]; then
    rm -R -- "$eval_owned_state" || {
      echo "eval: failed to remove owned scratch state at $eval_owned_state" >&2
      return 1
    }
  fi
  EVAL_STATE=
  EVAL_STATE_PARENT=
  EVAL_STATE_OWNED=0
  return 0
}

eval_finish() { # desired exit status
  eval_finish_status=$1
  trap - EXIT INT TERM
  eval_cleanup_status=0
  eval_down || eval_cleanup_status=$?
  if [ "$eval_finish_status" -eq 0 ] && [ "$eval_cleanup_status" -ne 0 ]; then
    eval_finish_status=$eval_cleanup_status
  fi
  exit "$eval_finish_status"
}
