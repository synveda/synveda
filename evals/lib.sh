# The controlled setup half of an eval run (EVAL-1, ADR-0028 decision 7).
#
# Tenant admission uses the exact migrator credential supplied by the isolated
# database fixture. Root/admin JIT, scope creation, service registration and
# every grant then use the governed gateway APIs under ordinary runtime roles.
# Sourced by evals/run.sh and demos/eval-1-harness.sh.
#
# eval_up    starts gateway/worker on a fresh exact-role database and writes $EVAL_ENV
# eval_run   runs the harness against it
# eval_down  puts everything back
#
# Callers set -eu and route exit or signals through eval_finish. Disable
# inherited tracing before any private file path or generated secret expands.
set +x

