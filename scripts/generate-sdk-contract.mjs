#!/usr/bin/env node
// ADPT-4: select a public contract slice; existing/maintained generators own types.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";

const check = process.argv.includes("--check");
const source = readFileSync("docs/api/openapi.json", "utf8");
const api = JSON.parse(source);
const selected = JSON.parse(readFileSync("sdks/operations.json", "utf8"));
const pending = new Set(selected);
const paths = {};
const operations = {};
const bindings = ["# GENERATED by scripts/generate-sdk-contract.mjs.\nfrom __future__ import annotations\nfrom typing import Any\nfrom . import models\nfrom .client import Client, ApiResponse\n"];
for (const [path, item] of Object.entries(api.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!pending.has(operation.operationId)) continue;
    pending.delete(operation.operationId);
    (paths[path] ??= {})[method] = operation;
    operations[operation.operationId] = {
      path, method: method.toUpperCase(),
      idempotent: (operation.parameters ?? []).some((p) => p.in === "header" &&
        p.name.toLowerCase() === "idempotency-key" && p.required),
      body: operation.requestBody?.required === true,
      accepts_body: operation.requestBody !== undefined,
      parameters: (operation.parameters ?? []).filter((p) => p.in === "path" || p.in === "query")
        .map(({ name, in: location, required }) => ({ name, location, required: required === true })),
    };
    const bodySchema = operation.requestBody?.content?.["application/json"]?.schema;
    const responseSchema = Object.entries(operation.responses).find(([code]) => /^2\d\d$/.test(code))?.[1].content?.["application/json"]?.schema;
    const pyType = (schema) => schema?.$ref ? `models.${schema.$ref.split("/").at(-1)}` : "Any";
    const bodyParameter = bodySchema ? `, body: ${pyType(bodySchema)}` : "";
    const keyParameter = operations[operation.operationId].idempotent ? "idempotency_key: str" : "idempotency_key: str | None = None";
    bindings.push(`async def ${operation.operationId}(client: Client${bodyParameter}, *, ${keyParameter},\n` +
      `    path: dict[str, str] | None = None, query: dict[str, str | int | bool | None] | None = None,\n` +
      `    traceparent: str | None = None) -> ApiResponse[${pyType(responseSchema)}]:\n` +
      `    return await client.request(${JSON.stringify(operation.operationId)}, ${bodySchema ? "body=body, " : ""}path=path, query=query,\n` +
      `        idempotency_key=idempotency_key, traceparent=traceparent)\n`);
  }
}
if (pending.size) throw new Error(`Unknown SDK operations: ${[...pending].join(", ")}`);

// A reachability walk only selects schemas. It does not interpret their shape.
const schemas = { ApiErrorBody: api.components.schemas.ApiErrorBody };
const work = [paths, schemas.ApiErrorBody];
for (let index = 0; index < work.length; index += 1) {
  const value = work[index];
  if (!value || typeof value !== "object") continue;
  if (value.$ref) {
    const name = value.$ref.replace("#/components/schemas/", "");
    if (!api.components.schemas[name]) throw new Error(`Unsupported reference: ${value.$ref}`);
    if (!schemas[name]) { schemas[name] = api.components.schemas[name]; work.push(schemas[name]); }
  }
  work.push(...Object.values(value).filter((v) => v && typeof v === "object"));
}
const contract = { openapi_sha256: createHash("sha256").update(source).digest("hex"), operations };
const scratch = mkdtempSync(join(tmpdir(), "synveda-sdk-generation-"));
function emit(path, bytes) {
  if (check) {
    if (!readFileSync(path).equals(Buffer.from(bytes))) throw new Error(`${path} is out of date`);
  } else {
    mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, bytes);
  }
}
try {
  const input = join(scratch, "openapi.json");
  writeFileSync(input, JSON.stringify({ ...api, paths, components: { ...api.components, schemas } }));
  const ts = join(scratch, "api.ts");
  execFileSync(process.execPath, ["scripts/generate-api-types.mjs", "--input", input, "--output", ts], { stdio: "pipe" });
  emit("sdks/typescript/src/generated/api.ts", readFileSync(ts));
  const py = join(scratch, "models.py");
  execFileSync(process.env.SYNVEDA_DATAMODEL_CODEGEN || "datamodel-codegen", [
    "--input", input, "--input-file-type", "openapi", "--output", py,
    "--output-model-type", "typing.TypedDict", "--target-python-version", "3.11",
    "--use-standard-collections", "--use-union-operator", "--disable-timestamp",
  ], { stdio: "pipe" });
  emit("sdks/python/synveda/models.py", readFileSync(py));
  emit("sdks/python/synveda/operations.py", `${bindings.join("\n").trimEnd()}\n`);
  emit("sdks/typescript/src/generated/contract.ts",
    `// GENERATED by scripts/generate-sdk-contract.mjs.\nexport const contract = ${JSON.stringify(contract, null, 2)} as const;\n`);
  emit("sdks/python/synveda/contract.json", `${JSON.stringify(contract, null, 2)}\n`);
  console.log(`SDK contract ${check ? "verified" : "generated"}: ${selected.length} operations, ${Object.keys(schemas).length} schemas`);
} finally { rmSync(scratch, { recursive: true, force: true }); }
